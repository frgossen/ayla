"""Tests for the readable, expandable PTX lifter."""
import textwrap

from ayla.ptx_python_codegen import main, ptx_to_python


def _unroll(source):
    namespace = {}
    exec(source, namespace)
    return namespace["PTX_PROGRAM"]()


def _nonempty_lines(source):
    return [line for line in source.splitlines() if line.strip()]


def _program_lines(source):
    lines = []
    for line in source.splitlines():
        code = line.split("//", 1)[0].rstrip()
        if code.strip():
            lines.append(code)
    return lines


def test_cli_converts_existing_ptx(tmp_path):
    input_path = tmp_path / "input.ptx"
    output_path = tmp_path / "output.py"
    input_path.write_text(".version 9.0\n")

    assert main([str(input_path), "-o", str(output_path)]) == 0

    source = output_path.read_text()
    assert "PTX_HEADER" in source
    assert "# PTX source: 1 total lines; 1 non-empty; 1 unique non-empty" in source
    assert "# Semantic schedule: 1 block occurrences; 1 unique block kinds" in source
    compile(source, str(output_path), "exec")
    assert _nonempty_lines(_unroll(source)) == [".version 9.0"]


def test_generic_external_ptx_runs_are_retained_for_full_unroll():
    ptx = textwrap.dedent("""\
        //
        // Generated by LLVM NVPTX Back-End
        //
        .version 9.0
        .target sm_90a
        .address_size 64
        .visible .entry external_kernel()
        {
        mov.b32 %r0, %r1;
        mov.b32 %r1, %r2;
        mov.b32 %r2, %r3;
        mov.b32 %r3, %r4;
        mov.b32 %r4, %r5;
        mov.b32 %r5, %r6;
        mov.b32 %r6, %r7;
        mov.b32 %r7, %r8;
        mov.b32 %r8, %r9;
        mov.b32 %r9, %r10;
        mov.b32 %r10, %r11;
        mov.b32 %r11, %r12;
        mov.b32 %r12, %r13;
        mov.b32 %r13, %r14;
        mov.b32 %r14, %r15;
        mov.b32 %r15, %r16;
        mbarrier.init.shared::cta.b64 [%r0], 1;
        ret;
        }
    """)

    source = ptx_to_python(ptx)

    assert "Generated by LLVM" not in source
    assert "\nPTX =" in source
    assert "emit(PTX)" in source
    assert "MBARRIER_INIT =" in source
    assert "KERNEL_RETURN =" in source
    assert "# PTX source: 27 total lines; 27 non-empty; 26 unique non-empty" in source
    compile(source, "<external-readable-ptx>", "exec")
    assert _program_lines(_unroll(source)) == _program_lines(ptx)


def test_affine_instruction_run_becomes_python_loop():
    ptx = textwrap.dedent("""\
        .version 9.0

        // PTX template `convert(%dst, %src)`
        cvt.rn.bf16x2.f32 %r10, %f1, %f0;
        cvt.rn.bf16x2.f32 %r11, %f3, %f2;
        cvt.rn.bf16x2.f32 %r12, %f5, %f4;
        cvt.rn.bf16x2.f32 %r13, %f7, %f6;
    """)

    source = ptx_to_python(ptx)

    assert "CONVERT =" in source
    assert "for i in range(4):" in source
    assert "%r{10 + i}" in source
    assert "%f{0 + 2 * i}" in source
    assert "%f{1 + 2 * i}" in source
    compile(source, "<readable-ptx>", "exec")


def test_repeated_multiline_pattern_becomes_one_loop():
    ptx = textwrap.dedent("""\
        // PTX template `move(%dst, %src)`
        ld.global.b32 %r0, [%rd0+0];
        add.u32 %r1, %r0, 1;
        ld.global.b32 %r2, [%rd1+16];
        add.u32 %r3, %r2, 1;
        ld.global.b32 %r4, [%rd2+32];
        add.u32 %r5, %r4, 1;
    """)

    source = ptx_to_python(ptx)

    assert "for i in range(3):" in source
    assert "ld.global.b32 %r{0 + 2 * i}, [%rd{0 + i}+{0 + 16 * i}];" in source
    assert "add.u32 %r{1 + 2 * i}, %r{0 + 2 * i}, 1;" in source
    compile(source, "<readable-ptx>", "exec")


