def test_external_kernel_declaration_is_one_occurrence_and_unrolls_once():
    registers = "\n".join(f"mov.b32 %r{i}, %r{i + 1};" for i in range(24))
    ptx = textwrap.dedent(f"""\
        .version 9.0
        .target sm_90a
        .address_size 64
        .visible .entry external_kernel(
            .param .u64 ptr
        )
        .reqntid 256
        {{
            .reg .b32 %r<26>;
        {registers}
            ret;
        }}
    """)

    source = ptx_to_python(ptx)

    assert "# 1 occurrence(s) in the full schedule" in source
    assert "KERNEL_DECLARATION =" in source
    assert source.count("emit(KERNEL_DECLARATION)") == 1
    unrolled = _unroll(source)
    assert unrolled.count(".visible .entry") == 1
    assert _program_lines(unrolled) == _program_lines(ptx)


def test_full_block_sequence_is_folded_before_instruction_details():
    iteration = textwrap.dedent("""\
        // PTX template `async(%lock: lock<mbar>) {...`
        cp.async.bulk.tensor.2d.shared::cluster.global;

        // PTX template `await(%lock: lock<mbar>)`
        mbarrier.try_wait.parity.shared::cta.b64;

        // PTX template `async(%lock: lock<wgmma>) {...`
        wgmma.mma_async.sync.aligned.m64n256k16;
    """)

    source = ptx_to_python("\n".join([iteration] * 3))

    assert "for repeat_0 in range(3):" in source
    assert source.count("emit(TMA_LOAD)") == 1
    assert source.count("emit(TMA_LOAD_WAIT)") == 1
    assert source.count("emit(WGMMA)") == 1
    compile(source, "<readable-ptx>", "exec")


def test_register_variants_share_one_parameterized_definition():
    ptx = "\n\n".join(
        f"cp.async.bulk.tensor.2d.shared::cta.global.mbarrier::complete_tx::bytes "
        f"[%r{10 + i}], [%rd{20 + i}, {{%r{30 + i}, %r{40 + i}}}], "
        f"[%r{50 + i}];"
        for i in range(3)
    )

    source = ptx_to_python(ptx)

    assert source.count("_tma_load_template =") == 1
    assert "# 3 occurrence(s) in the full schedule" in source
    assert "for repeat_0 in range(3):" in source
    assert source.count("emit(TMA_LOAD)") == 1
    assert _program_lines(_unroll(source)) == _program_lines(ptx)


def test_barrier_scopes_remain_distinct_blocks():
    ptx = textwrap.dedent("""\
        // PTX template `barrier() attrs={reason: "mbarrier_init", scope: "block"}`
        bar.sync 0;

        // PTX template `barrier() attrs={id: 1, scope: "block_leader"}`
        @%p0 bar.sync 1, 256;
        @!%p0 bar.arrive 1, 256;
    """)

    source = ptx_to_python(ptx)

    assert "MBARRIER_INIT_SYNC =" in source
    assert "BLOCK_LEADER_BARRIER =" in source
    compile(source, "<readable-ptx>", "exec")


def test_unannotated_compiler_ptx_exposes_pipeline_operations():
    body = [".visible .entry external_kernel()", ".reqntid 256, 1, 1", "{"]
    body.extend(f"mov.b32 %r{i}, %r{i + 1};" for i in range(24))
    body.extend([
        "mbarrier.try_wait.parity.shared::cta.b64 %p0, [%r0], %r1;",
        "cp.async.bulk.tensor.2d.shared::cta.global.tile.mbarrier::complete_tx::bytes [%r0], [%rd0, {%r1, %r2}], [%r3];",
        "wgmma.fence.sync.aligned;",
        "wgmma.mma_async.sync.aligned.m64n256k16.f32.bf16.bf16;",
        "wgmma.commit_group.sync.aligned;",
        "wgmma.wait_group.sync.aligned 0;",
        "stmatrix.sync.aligned.m8n8.x4.shared.b16;",
        "cp.async.bulk.tensor.2d.global.shared::cta.tile.bulk_group;",
        "cp.async.bulk.commit_group;",
        "cp.async.bulk.wait_group.read 0;",
        "ret;",
        "}",
    ])

    source = ptx_to_python("\n".join(body))

    for name in (
        "TMA_LOAD_WAIT", "TMA_LOAD", "WGMMA_FENCE", "WGMMA",
        "WGMMA_COMMIT", "WGMMA_WAIT", "STMATRIX_STORE", "TMA_STORE",
        "TMA_STORE_COMMIT", "TMA_STORE_WAIT",
    ):
        assert f"{name} =" in source
    compile(source, "<external-readable-ptx>", "exec")
